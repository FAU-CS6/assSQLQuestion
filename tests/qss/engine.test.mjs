import {createEditGraph, replayOperation} from '../../lib/qss/src/graph-edits.mjs';

const sandbox = {setTimeout, clearTimeout, AbortController};
vm.createContext(sandbox);
vm.runInContext(readFileSync(new URL('../../lib/qss/qss.js', import.meta.url), 'utf8'), sandbox);
const QSS = sandbox.QSS;
const schema = {tables: [
    {name: 'items', columns: [{name: 'id', type: 'INTEGER'}, {name: 'amount', type: 'REAL'}, {name: 'name', type: 'TEXT'}]},
    {name: 'details', columns: [{name: 'item_id', type: 'INTEGER'}, {name: 'active', type: 'INTEGER'}]}
]};
// Fixed-scale graph tests retain an explicit scale; relative defaults have a
// separate contract suite with several different question maxima.
const evaluate = (reference, answer, extra = {}) => QSS.evaluate({reference, answer, schema, maxPoints: 5, scale:1, ...extra});
const plain = value => JSON.parse(JSON.stringify(value));
const editCost = result => result.edits.reduce((sum, edit) => sum + edit.cost, 0);
const round = value => Math.round((value + Number.EPSILON) * 10000) / 10000;
function scored(result, maximum = 5) {
    assert.ok(['exact', 'score-zero-certified'].includes(result.status), JSON.stringify(result));
    assert.equal(result.engine, 'graph-qss-sqlite-v2');
    assert.equal(result.version, '2.1.1');
    assert.equal(result.rubric, 'paper-linear-v2');
    assert.equal(result.scoreCertifiedWithinModel, true);
    assert.ok(Number.isFinite(result.points) && result.points >= 0 && result.points <= maximum);
    if (result.status === 'exact') {
        assert.equal(result.points, round(Math.max(maximum - result.distance * result.scale, 0)));
        assert.equal(result.exactWithinModel, true);
        assert.equal(editCost(result), result.distance);
    } else {
        assert.equal(result.distance, null);
        assert.equal(result.points, 0);
        assert.ok(result.lowerBound >= maximum / result.scale);
    }
}
function trace(reference, answer, result, extra = {}) {
    assert.equal(result.status, 'exact');
    const activeSchema = Object.hasOwn(extra, 'schema') ? extra.schema : schema;
    const target = parseGraphSql(reference, {schema: activeSchema}).root;
    let current = parseGraphSql(answer, {schema: activeSchema, allowEmpty: true}).root;
    const graph = createEditGraph(target, current, activeSchema, extra.costs);
    for (const step of plain(result.edits)) {
        const edit = graph.edits.find(value => value.name === step.name);
        assert.ok(edit, 'Every step names an actual configured SQL edit.');
        assert.equal(step.cost, edit.cost);
        assert.equal(step.operation.name, edit.name);
        const next = replayOperation(current, step.operation);
        assert.ok([...edit.apply(current)].some(value => stableKey(value.root) === stableKey(next)),
            'The replayed transition is generated by its declared neighbour function.');
        current = next;
    }
    assert.equal(stableKey(current), stableKey(target));
    assert.equal(editCost(result), result.distance);
    return current;
}
async function zeroPath(reference, answer, extra = {}) {
    const result = await evaluate(reference, answer, extra);
    scored(result);
    assert.equal(result.status, 'exact');
    assert.equal(result.distance, 0);
    assert.equal(result.points, 5);
    trace(reference, answer, result, extra);
    const activeSchema = Object.hasOwn(extra, 'schema') ? extra.schema : schema;
    if (stableKey(parseGraphSql(reference, {schema: activeSchema}).root) !== stableKey(parseGraphSql(answer, {schema: activeSchema}).root)) {
        assert.ok(result.edits.length > 0, 'Semantic equivalence requires actual graph edges, not precanonicalized node equality.');
        assert.ok(result.edits.every(edit => edit.cost === 0));
    }
    return result;
}

test('graph identity and the paper linear grading contract are explicit', async () => {
    const result = await evaluate('SELECT id FROM items', 'SELECT id FROM items');
    scored(result);
    assert.equal(QSS.GRAPH_ENGINE, 'graph-qss-sqlite-v2');
    assert.equal(QSS.SYNTAX_ENGINE, undefined);
    assert.equal(result.distance, 0);
    assert.equal(result.scale, 1);
    assert.equal(result.provisionalRubric, true);
    assert.equal(result.referenceDistance, null);
    assert.equal(result.normalizationDistance, null);
    assert.match(result.formula, /maxPoints.*distance.*scale/);
    assert.ok(result.limitations.some(value => /human-graded/.test(value)));
    assert.deepEqual(plain(result.edits), []);
});

test('whitespace, comments, keyword case and final semicolon have identical ASTs', async () => {
    await zeroPath('SELECT id FROM items', 'select /* safe */ id\nfrom items; -- trailing');
});

test('bound alias changes use actual zero-cost SQL edit edges', async () => {
    const result = await zeroPath('SELECT first.id FROM items first', 'SELECT second.id FROM items second');
    assert.ok(result.edits.some(edit => edit.name === 'renameBoundTableAlias'));
    const wrong = await evaluate('SELECT first.id FROM items first, details second', 'SELECT second.active FROM items first, details second');
    scored(wrong); assert.ok(wrong.points < 5);
});

test('correlated alias edits preserve inner and outer binding scopes', async () => {
    const reference = 'SELECT a.id FROM items a WHERE EXISTS(SELECT 1 FROM details d WHERE d.item_id=a.id);';
    await zeroPath(reference, 'SELECT x.id FROM items x WHERE EXISTS(SELECT 1 FROM details y WHERE y.item_id=x.id);');
    const wrong = await evaluate(reference, 'SELECT a.id FROM items a WHERE EXISTS(SELECT 1 FROM details d WHERE d.item_id=d.active);');
    scored(wrong); assert.ok(wrong.points < 5);
    const unbound = await evaluate('SELECT a.id FROM items a WHERE EXISTS(SELECT 1 FROM details d WHERE d.item_id=id);',
        'SELECT a.id FROM items a WHERE EXISTS(SELECT 1 FROM details d WHERE d.item_id=d.active);', {schema: undefined});
    scored(unbound); assert.ok(unbound.points < 5);
});

test('leading underscore identifiers are represented without parser recovery', async () => {
    await zeroPath('SELECT 0 AS __qss_wrong_answer__;', 'SELECT 0 AS __qss_wrong_answer__;');
});

test('pure AND reordering and comparison mirroring form zero-cost paths', async () => {
    await zeroPath('SELECT id FROM items WHERE id > 0 AND amount < 9', 'SELECT id FROM items WHERE amount < 9 AND 0 < id');
});

test('opposite comparisons cost one SQL operator edit; equivalent mirrors cost zero', async () => {
    for (const [operator, opposite] of [['>', '<'], ['<', '>'], ['>=', '<='], ['<=', '>=']]) {
        const reference = `SELECT id FROM items WHERE amount${operator}10`;
        const answer = `SELECT id FROM items WHERE amount${opposite}10`;
        const wrong = await evaluate(reference, answer, {exactDistance: true});
        scored(wrong); assert.equal(wrong.distance, 1); assert.equal(wrong.points, 4);
        trace(reference, answer, wrong);
        await zeroPath(reference, `SELECT id FROM items WHERE 10${opposite}amount`);
    }
});

test('NOT equality and inequality use zero edges under SQL NULL semantics', async () => {
    for (const value of ['1', 'NULL']) await zeroPath(`SELECT id FROM items WHERE id <> ${value}`, `SELECT id FROM items WHERE NOT(id = ${value})`);
});

test('INNER JOIN conditions move through actual zero-cost graph edges', async () => {
    const result = await zeroPath('SELECT items.id FROM items INNER JOIN details ON items.id=details.item_id', 'SELECT items.id FROM items, details WHERE items.id=details.item_id');
    assert.ok(result.edits.some(edit => edit.name === 'relocateInnerJoinPredicate'));
});

test('the INNER JOIN shortcut excludes outer joins and preserves star column order', async () => {
    const wrong = await evaluate('SELECT items.id FROM items LEFT JOIN details ON items.id=details.item_id',
        'SELECT items.id FROM items, details WHERE items.id=details.item_id');
    scored(wrong); assert.ok(wrong.points < 5);
    await zeroPath('SELECT * FROM items INNER JOIN details ON items.id=details.item_id',
        'SELECT * FROM items, details WHERE items.id=details.item_id');
});

