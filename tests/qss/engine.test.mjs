test('manual cancellation is per job and never certifies a score', async () => {
    const controller = new AbortController();
    const pending = QSS.evaluate({reference: 'SELECT id FROM items', answer: 'SELECT amount FROM items', maxPoints: 5},
        () => controller.abort(), {signal: controller.signal});
    const [cancelled, unaffected] = await Promise.all([pending, evaluate('SELECT id FROM items', 'SELECT id FROM items')]);
    assert.equal(cancelled.status, 'cancelled'); assert.equal(cancelled.points, null); assert.equal(unaffected.points, 5);
});

test('worker progress/results retain their per-request identifiers', () => {
    const handlers = [], messages = [];
    const local = {setTimeout, clearTimeout, AbortController, self: {addEventListener: (_, listener) => handlers.push(listener), postMessage: value => messages.push(plain(value))}};
    vm.createContext(local);
    vm.runInContext(readFileSync(new URL('../../lib/qss/worker.qss.js', import.meta.url), 'utf8'), local);
    assert.equal(handlers.length, 1);
    return handlers[0]({data: {type: 'evaluate', id: 'isolated', reference: 'SELECT 1', answer: 'SELECT 1', maxPoints: 1}}).then(() => {
        assert.equal(messages[0].id, 'isolated'); assert.equal(messages.at(-1).type, 'result'); assert.equal(messages.at(-1).result.points, 1);
        assert.equal(messages.at(-1).result.engine, 'graph-qss-sqlite-v2');
    });
});
